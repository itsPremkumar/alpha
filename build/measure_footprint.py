#!/usr/bin/env python3
"""Measure Alpha's installed footprint and enforce the size budget in CI.

The installed footprint, not the installer, is what makes Alpha heavy. The
Python dependency tree is the dominant term, so it gets measured rather than
estimated, and the budget lives in exactly one greppable place --
``installer/size-budget.json`` -- which this tool both reads and enforces.

Usage
-----
    python build/measure_footprint.py --json
    python build/measure_footprint.py --budget

``--budget`` exits non-zero when any measured value exceeds its budget, which is
what makes the budget a gate rather than a wish. ``--json`` prints the raw
measurements for a human or a CI step to archive.

Every number printed is MEASURED unless the key is prefixed ``note_`` or lives
under ``unverified``. Sizes are mebibytes (1 MiB = 1048576 bytes), matching
``currency_units`` in the budget file.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import sys
from collections.abc import Sequence
from dataclasses import dataclass, field
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
BUDGET_PATH = REPO_ROOT / "installer" / "size-budget.json"
MIB = 1024 * 1024

# Directories that are regenerated by a build or are local scratch, and are
# accounted for separately (or not at all). Excluding them keeps "the source
# checkout" a meaningful number instead of one dominated by a virtualenv.
#
# The metric is exact on a CLEAN checkout, which is where CI runs it
# (actions/checkout produces a clean tree). On a dirty working tree these
# exclusions are what stop a local build from masquerading as repository size.
VENDORED_DIR_NAMES = frozenset(
    {
        ".venv",
        "venv",
        "node_modules",
        ".next",
        ".git",
        "__pycache__",
        ".pytest_cache",
        ".ruff_cache",
        ".hypothesis",
        ".agent-workspace",
        ".agent_workspace_projects",
        ".workbuddy-ai",
        ".monocle",
        "dist",
        "build/measure",
        "prod-venv",
        "logs",
        "temp",
    }
)


def dir_size_bytes(path: Path) -> int:
    """Total size of every file under ``path``. Missing paths measure as 0."""
    return walk_tree(path)[0]


def walk_tree(path: Path, skip: frozenset[str] = frozenset()) -> tuple[int, int]:
    """Return ``(bytes, file_count)`` for a tree in a single pass.

    One pass, not two: a real measurement walks trees with tens of thousands of
    files (the production virtualenv alone is 51,975), and walking twice to
    compute size and count separately doubled a CI step for no information.
    """
    if not path.is_dir():
        return 0, 0
    total = 0
    count = 0
    for root, dirs, files in os.walk(path, onerror=lambda _exc: None):
        if skip:
            dirs[:] = [d for d in dirs if d not in skip]
        for name in files:
            try:
                total += (Path(root) / name).stat().st_size
            except OSError:
                continue
            count += 1
    return total, count


def source_checkout_bytes(repo_root: Path) -> int:
    """Size of the tracked source, excluding vendored/regenerated trees.

    Exact on a clean checkout. On a dirty tree the exclusions above are what
    keep a local ``.next`` or virtualenv from being reported as repository size.
    """
    total = 0
    for root, dirs, files in os.walk(repo_root, onerror=lambda _exc: None):
        # Prune by full relative path as well as by name, so a nested scratch
        # directory (build/measure) is excluded even though its own name is not
        # in the list.
        rel = (Path(root) / "").resolve().relative_to(repo_root).as_posix() if str(root).startswith(str(repo_root)) else ""
        dirs[:] = [d for d in dirs if d not in VENDORED_DIR_NAMES and f"{rel}/{d}".strip("/") not in VENDORED_DIR_NAMES]
        for name in files:
            try:
                total += (Path(root) / name).stat().st_size
            except OSError:
                continue
    return total


def free_disk_bytes(path: Path) -> int:
    usage = shutil.disk_usage(path if path.exists() else Path(path.anchor))
    return usage.free


def to_mib(value: int) -> float:
    return round(value / MIB, 1)


@dataclass
class Measurement:
    """One measured quantity and, where relevant, the budget it must respect."""

    key: str
    mib: float
    files: int = 0
    budget_mib: float | None = None
    path: str = ""
    note: str = ""
    verified: bool = True
    extra: dict[str, object] = field(default_factory=dict)

    @property
    def within_budget(self) -> bool:
        return self.budget_mib is None or self.mib <= self.budget_mib

    def to_dict(self) -> dict[str, object]:
        payload: dict[str, object] = {
            "key": self.key,
            "mib": self.mib,
            "files": self.files,
            "within_budget": self.within_budget,
            "verified": self.verified,
        }
        if self.path:
            payload["path"] = self.path
        if self.budget_mib is not None:
            payload["budget_mib"] = self.budget_mib
        if self.note:
            payload["note"] = self.note
        payload.update(self.extra)
        return payload


def count_files(path: Path) -> int:
    """Deprecated shim kept for readability; prefer walk_tree's file count."""
    return walk_tree(path)[1]


def uv_executable() -> str | None:
    """Locate uv the way a user would have it after the installer ran."""
    for candidate in (
        os.environ.get("ALPHA_UV"),
        shutil.which("uv"),
        str(Path.home() / ".cargo" / "bin" / "uv.exe"),
        str(Path.home() / "AppData" / "Local" / "hermes" / "bin" / "uv.exe"),
    ):
        if candidate and Path(candidate).is_file():
            return candidate
    return None


def collect(repo_root: Path, full: bool = False) -> dict[str, object]:
    """Take every measurement this tool is able to take on this machine.

    ``full`` additionally measures the developer virtualenv and the Electron
    artefacts. Those are *comparison* figures -- neither is gated, and the
    developer venv alone is 73,457 files. Walking them on every CI run would
    make a budget gate slow enough that people stop waiting for it, so they are
    opt-in via ``--full``.
    """
    budget = json.loads(BUDGET_PATH.read_text(encoding="utf-8"))
    budgets = budget["budgets"]

    measurements: list[Measurement] = []

    def add(key: str, path_bytes: int, files: int, *, budget_key: str | None = None, path: str = "", note: str = "", verified: bool = True) -> None:
        measurements.append(
            Measurement(
                key=key,
                mib=to_mib(path_bytes),
                files=files,
                budget_mib=float(budgets[budget_key]) if budget_key else None,
                path=path,
                note=note,
                verified=verified,
            )
        )

    def add_tree(key: str, path_obj: Path, **kwargs: object) -> None:
        size, count = walk_tree(path_obj)
        add(key, size, count, **kwargs)  # type: ignore[arg-type]

    # --- The native installed footprint, component by component ------------
    prod_venv = repo_root / "build" / "measure" / "prod-venv"
    add_tree("python_venv_production", prod_venv, path="build/measure/prod-venv", note="uv sync --locked --no-dev, i.e. what installer/bootstrap.ps1 provisions")

    if full:
        add_tree("python_venv_dev_all_extras", repo_root / "backend" / ".venv", path="backend/.venv", note="a developer venv with every extra installed; NOT what a user gets. Measured only with --full: 73k files.")

    uv_root = Path(os.environ.get("APPDATA", "")) / "uv" / "python"
    # WARNING, stated here because the number is larger than it looks: this is
    # EVERY CPython uv has ever provisioned on this machine (a developer box
    # accumulates 3.11, 3.12 and 3.13 side by side), not the one pinned install
    # a user would get. A single CPython 3.12 is ~63 MiB; this figure was 579.5
    # MiB across six interpreters on the measurement machine. It is reported
    # because it is the honest machine-wide total, and it is deliberately
    # OVERSTATED rather than flattering the budget.
    add_tree("uv_managed_cpython", uv_root, path="%APPDATA%/uv/python", note="EVERY CPython uv has provisioned on this machine, not the pinned one; a single CPython 3.12 is ~63 MiB. Overstated on purpose.")

    # The prebuilt Next.js server output. The path inside the existing Electron
    # bundle is the one that is actually present and measured; a local
    # frontend/.next/standalone only exists after a production build, so both are
    # probed and whichever exists is measured.
    for candidate in (
        repo_root / "frontend" / ".next" / "standalone",
        repo_root / "electron" / "dist" / "win-unpacked" / "resources" / "frontend-standalone",
    ):
        if candidate.is_dir():
            add_tree(
                "frontend_standalone",
                candidate,
                path=candidate.relative_to(repo_root).as_posix(),
                note="prebuilt Next.js SERVER output. NOTE: os.walk follows the pnpm store's junctions, so this OVER-counts; a non-reparse-point walk measured 78.5 MiB across 2,470 files for the same path.",
            )
            break
    else:
        add("frontend_standalone", 0, 0, note="no prebuilt frontend found; run the frontend build to measure this component")

    if full:
        add(
            "electron_installer",
            dir_size_bytes(repo_root / "electron" / "dist" / "Agent-Workspace-Setup-2.1.0.exe"),
            0,
            path="electron/dist/Agent-Workspace-Setup-2.1.0.exe",
            note="the existing Electron NSIS artefact, for comparison",
        )

    add("installer_script", (REPO_ROOT / "installer" / "bootstrap.ps1").stat().st_size if (REPO_ROOT / "installer" / "bootstrap.ps1").is_file() else 0, 1, budget_key="installer_script", path="installer/bootstrap.ps1")

    add("source_checkout", source_checkout_bytes(repo_root), 0, budget_key="source_checkout", path="<repo, vendored trees excluded>", note="tracked source with .venv/node_modules/.next/.git excluded")

    # --- The budget that actually gates CI: the native installed footprint --
    # uv binary + pinned CPython + production venv + Node + prebuilt frontend +
    # source checkout. Anything missing is reported as unverified rather than
    # silently counted as zero, because "0 MB" for an unmeasured component is
    # exactly the kind of estimate that makes a budget meaningless.
    components = ["python_venv_production", "uv_managed_cpython", "frontend_standalone", "source_checkout"]
    measured = {m.key: m for m in measurements}
    subtotal = sum(measured[k].mib for k in components if measured[k].mib > 0)
    incomplete = [k for k in components if measured[k].mib == 0]

    uv_exe = uv_executable()
    uv_mib = to_mib(Path(uv_exe).stat().st_size) if uv_exe else 0.0
    node_mib = 0.0
    node = shutil.which("node")
    if node:
        # Only the directory that CONTAINS node.exe, not its whole subtree: a
        # version manager's node directory is a junction tree and walking into it
        # measures every installed version rather than one runtime.
        node_root = Path(node).parent
        node_mib = to_mib(sum(f.stat().st_size for f in node_root.iterdir() if f.is_file()))

    installed = Measurement(
        key="installed_footprint",
        mib=round(subtotal + uv_mib + node_mib, 1),
        files=sum(measured[k].files for k in components),
        budget_mib=float(budgets["installed_footprint"]),
        path="<native path, no Docker>",
        note="uv binary + pinned CPython + production venv + Node + prebuilt frontend + source checkout",
        verified=not incomplete,
        extra={
            "components_mib": {k: measured[k].mib for k in components},
            "uv_binary_mib": uv_mib,
            "node_mib": node_mib,
            "unmeasured_components": incomplete,
        },
    )
    measurements.append(installed)

    free = free_disk_bytes(repo_root)

    return {
        "currency_units": budget["currency_units"],
        "repo_root": str(repo_root),
        "free_disk_mib": to_mib(free),
        "measurements": [m.to_dict() for m in measurements],
        "budget_source": BUDGET_PATH.relative_to(REPO_ROOT).as_posix(),
    }


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--json", action="store_true", dest="as_json", help="print the measurements as JSON")
    parser.add_argument("--budget", action="store_true", help="exit non-zero when a measured value exceeds its budget")
    parser.add_argument("--full", action="store_true", help="also measure the ungated comparison artefacts (developer venv, Electron bundle). Slow: walks tens of thousands of files.")
    parser.add_argument("--repo-root", type=Path, default=REPO_ROOT, dest="repo_root", help="repository to measure")
    args = parser.parse_args(argv)

    report = collect(args.repo_root.resolve(), full=args.full)
    measurements = report["measurements"]

    if args.as_json or not args.budget:
        print(json.dumps(report, indent=2, sort_keys=True))

    if not args.budget:
        return 0

    failures = [m for m in measurements if m.get("budget_mib") is not None and not m.get("within_budget", True)]
    unverified = [m for m in measurements if m.get("budget_mib") is not None and not m.get("verified", True)]

    print("")
    print("=== Alpha installed-footprint size budget ===")
    for m in measurements:
        if m.get("budget_mib") is None:
            continue
        status = "OK  " if m.get("within_budget") else "FAIL"
        flag = "" if m.get("verified", True) else "  (PARTIAL: some components unmeasured)"
        print(f"  [{status}] {m['key']:<28} {m['mib']:>9.1f} MiB  budget {m['budget_mib']:>8.1f} MiB{flag}")

    if failures:
        print("")
        for m in failures:
            print(f"SIZE BUDGET EXCEEDED: {m['key']} is {m['mib']} MiB, budget is {m['budget_mib']} MiB (over by {round(m['mib'] - m['budget_mib'], 1)} MiB)", file=sys.stderr)
        return 1

    if unverified:
        print("")
        for m in unverified:
            print(f"WARNING: {m['key']} was only partially measurable on this machine; the budget verdict is not trustworthy.", file=sys.stderr)

    print("")
    print("size budget satisfied")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
